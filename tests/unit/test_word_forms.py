# (query, stored): other words that a query finds too, because they begin with a start of only
# three letters that the query word shares. The price of finding "кава" from "каву" without a
# dictionary; written down so that a change to it is a choice.
FINDS_TOO = [
    ("cars", "card"),
    ("this", "thing"),
    ("його", "йога"),
    ("тому", "томат"),
    ("мене", "менеджер"),
    ("колись", "колір"),
]


def finds(query: str, stored: str) -> bool:
    (word,) = words(stored)
    return any(term.count_in([word]) for term in query_terms(query))


@pytest.mark.parametrize(("query", "stored"), FINDS)
def test_a_word_finds_its_other_forms(query: str, stored: str) -> None:
    assert finds(query, stored)


@pytest.mark.parametrize(("query", "stored"), MISSES)
def test_a_short_word_does_not_find_longer_words_that_start_with_it(
    query: str, stored: str
) -> None:
    assert not finds(query, stored)


@pytest.mark.parametrize(("query", "stored"), FINDS_TOO)
def test_a_start_of_three_letters_also_finds_other_words(query: str, stored: str) -> None:
    assert finds(query, stored)
